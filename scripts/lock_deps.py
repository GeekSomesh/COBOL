"""Hash-pinned lock file and CycloneDX SBOM for the runtime dependencies.

    python scripts/lock_deps.py          # -> requirements.lock, sbom.cdx.json

1. ``pip install --dry-run --ignore-installed --report`` resolves the exact set of
   distributions ``requirements.txt`` needs (nothing is installed).
2. For each pinned version, the SHA-256 of every file PyPI publishes for it (all
   platforms, so the same lock serves Windows, Linux and the container) comes from
   PyPI's JSON API.
3. ``requirements.lock`` lists ``name==version --hash=sha256:...``; install it with
   ``pip install --require-hashes -r requirements.lock``. A package whose bytes differ
   from what PyPI published is refused.
4. ``sbom.cdx.json``: a CycloneDX 1.5 bill of materials (name, version, purl,
   licence when declared, hashes) for those components.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def resolve() -> list[dict]:
    with tempfile.TemporaryDirectory() as d:
        report = Path(d) / "report.json"
        subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
                        "--report", str(report), "-r", str(ROOT / "requirements.txt")], check=True)
        data = json.loads(report.read_text(encoding="utf-8"))
    out = []
    for item in data["install"]:
        meta = item["metadata"]
        out.append({"name": meta["name"], "version": meta["version"],
                    "license": meta.get("license_expression") or (meta.get("license") or "").split("\n")[0][:80]})
    return sorted(out, key=lambda x: x["name"].lower())


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as r:
        data = json.load(r)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def main() -> int:
    deps = resolve()
    lines = ["# Generated by scripts/lock_deps.py from requirements.txt. Install with:",
             "#   pip install --require-hashes -r requirements.lock", ""]
    components = []
    for d in deps:
        hs = hashes(d["name"], d["version"])
        lines.append(f"{d['name']}=={d['version']} \\")
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hs) - 1 else "") for i, h in enumerate(hs)]
        comp = {"type": "library", "name": d["name"], "version": d["version"],
                "purl": f"pkg:pypi/{d['name'].lower()}@{d['version']}",
                "hashes": [{"alg": "SHA-256", "content": h} for h in hs]}
        if d["license"]:
            comp["licenses"] = [{"expression": d["license"]}] if " " not in d["license"].strip() or \
                d["license"].count(" OR ") or d["license"].count(" AND ") else [{"license": {"name": d["license"]}}]
        components.append(comp)
        print(f"{d['name']}=={d['version']}: {len(hs)} files")
    (ROOT / "requirements.lock").write_text("\n".join(lines) + "\n", encoding="utf-8")
    sbom = {"bomFormat": "CycloneDX", "specVersion": "1.5", "version": 1,
            "metadata": {"timestamp": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                         "component": {"type": "application", "name": "cobol-to-decision", "version": "1.0.0"},
                         "tools": [{"name": "scripts/lock_deps.py"}]},
            "components": components}
    (ROOT / "sbom.cdx.json").write_text(json.dumps(sbom, indent=2), encoding="utf-8")
    print(f"wrote requirements.lock ({len(deps)} packages) and sbom.cdx.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
